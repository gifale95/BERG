"""Test the encoding models' predictions on the BMD test data, and save the
encoding accuracy as part of the encoding models' metadata.

BMD paper: https://doi.org/10.1038/s41467-024-50310-3
BMD data: https://openneuro.org/datasets/ds005165

Parameters
----------
subject : int
    Number of the used BMD subject.
model : str
	Name of the used encoding model.
berg_dir : str
    Directory of the Brain Encoding Response Generator (BERG).
    https://github.com/gifale95/BERG
bmd_dir : str
    Directory of the BOLD Moments Dataset (BMD).
    https://openneuro.org/datasets/ds005165

"""

import argparse
import os
import numpy as np
import nibabel as nib
import pickle
from copy import copy
from scipy.stats import pearsonr

parser = argparse.ArgumentParser()
parser.add_argument('--subject', type=int, default=1)
parser.add_argument('--model', type=str, default='s3d')
parser.add_argument('--berg_dir', default='/scratch/giffordale95/projects/brain-encoding-response-generator', type=str)
parser.add_argument('--bmd_dir', default='/scratch/giffordale95/projects/eeg_moments/bold_moments_dataset', type=str)
args, unknown = parser.parse_known_args()

print('>>> Test BMD encoding models <<<')
print('\nInput parameters:')
for key, val in vars(args).items():
    print('{:16} {}'.format(key, val))


# =============================================================================
# Get the group- and subject-level masks
# =============================================================================
mask_dir = os.path.join(args.bmd_dir, 'derivatives', 'versionB', 'MNI152',
    'GLM', 'mask')

group_mask = nib.load(os.path.join(mask_dir,
    'groupMask_space-MNI152.nii')).get_fdata().astype(bool)

sub_mask = nib.load(os.path.join(mask_dir,
    f'sub-{args.subject:02d}_mask-nonans_space-MNI152.nii')).get_fdata().astype(bool)


# =============================================================================
# Get the ROI indices
# =============================================================================
# ROI names
roi_names = [
    'lV1v', 'rV1v', 'lV1d', 'rV1d', 'lV2v', 'rV2v', 'lV2d', 'rV2d', 'lV3v',
    'rV3v', 'lV3d', 'rV3d', 'lV3ab', 'rV3ab', 'lhV4', 'rhV4',

    'lFFA', 'rFFA', 'lOFA', 'rOFA', 'lEBA', 'rEBA', 'lLOC', 'rLOC', 'lPPA',
    'rPPA', 'lRSC', 'rRSC', 'rSTS', 'lSTS', 'lTOS', 'rTOS',

    'lMT', 'rMT', 'l7AL', 'r7AL', 'lIPS0', 'rIPS0', 'rIPS1-2-3', 'lIPS1-2-3',
    'lPFt', 'rPFt', 'lBA2', 'rBA2', 'lPFop', 'rPFop',

    'BMDgeneral'
]

# Load the ROIs
rois = {}
for roi in roi_names:
    roi_dir = os.path.join(args.bmd_dir, 'derivatives', 'versionB', 'MNI152',
        'GLM', f'sub-{args.subject:02d}', 'ROIs', f'ROI-{roi}_indices.pkl')
    with open(roi_dir, "rb") as f:
        rois[roi] = pickle.load(f)


# =============================================================================
# Get the noise ceiling
# =============================================================================
betas_dir = os.path.join(args.bmd_dir, 'derivatives', 'versionB', 'MNI152',
    'GLM', f'sub-{args.subject:02d}', 'prepared_betas')

# Load the noise ceiling computed on singel train data repeats
file = os.path.join(betas_dir,
    f'sub-{args.subject:02d}_noiseceiling_task-train_n-1.pkl')
with open(file, "rb") as f:
    noiseceiling_task_train_n_1 = pickle.load(f)[1]

# Load the noise ceiling computed on all train data repeats
file = os.path.join(betas_dir,
    f'sub-{args.subject:02d}_noiseceiling_task-train_n-3.pkl')
with open(file, "rb") as f:
    noiseceiling_task_train_n_3 = pickle.load(f)[1]

# Load the noise ceiling computed on single test data repeats
file = os.path.join(betas_dir,
    f'sub-{args.subject:02d}_noiseceiling_task-test_n-1.pkl')
with open(file, "rb") as f:
    noiseceiling_task_test_n_1 = pickle.load(f)[1]

# Load the noise ceiling computed on all test data repeats
file = os.path.join(betas_dir,
    f'sub-{args.subject:02d}_noiseceiling_task-test_n-10.pkl')
with open(file, "rb") as f:
    noiseceiling_task_test_n_10 = pickle.load(f)[1]


# =============================================================================
# Load the BMD in vivo test betas
# =============================================================================
# Load the fMRI responses for the test images
fmri_file = os.path.join(args.bmd_dir, 'derivatives', 'versionB', 'MNI152',
    'GLM', f'sub-{args.subject:02d}', 'prepared_betas',
    f'sub-{args.subject:02d}_organized_betas_task-test_normalized.pkl')
with open(fmri_file, "rb") as f:
    fmri_test = pickle.load(f)[0]

# Average the responses across repeats
fmri_test = np.mean(fmri_test, 1)


# =============================================================================
# Load the BMD in silico test betas generated by the encoding models
# =============================================================================
betas_dir = os.path.join(args.berg_dir, 'results', 'test_encoding_models',
    'modality-fmri', 'train_dataset-bmd', 'model-'+args.model,
    f'betas_test_pred_sub-{args.subject:02d}.npy')

betas_test_pred = np.load(betas_dir)


# =============================================================================
# Compute the encoding model's prediction accuracy
# =============================================================================
# Correlate the predicted and actual fMRI responses for the test images,
# at each vertex
correlation = np.zeros(fmri_test.shape[1])
for v in range(fmri_test.shape[1]):
    correlation[v] = pearsonr(fmri_test[:,v], betas_test_pred[:,v])[0]

# Set negative correlation scores to zero
correlation[correlation<0] = 0

# Turn the correlations into r2 scores
r2 = correlation ** 2

# Add a very small number to noise ceiling values of 0, otherwise the
# noise-ceiling-normalized encoding accuracy cannot be calculated (division
# by 0 is not possible)
noiseceiling = copy(noiseceiling_task_test_n_10)
noiseceiling[noiseceiling==0] = 1e-14

# Compute the noise-ceiling-normalized encoding accuracy
explained_variance = np.divide(r2, noiseceiling) * 100

# Set the noise-normalized encoding accuracy to 100 for vertices where the
# the correlation is higher than the noise ceiling, to prevent encoding
# accuracy values higher than 100%
explained_variance[explained_variance>100] = 100


# =============================================================================
# Prepare and save the metadata
# =============================================================================
metadata = {
    'fmri': {
        'group_mask': group_mask,
        'sub_mask': sub_mask,
        'rois': rois
        },
    'encoding_models': {
        'noiseceiling_task_train_n_1': noiseceiling_task_train_n_1,
        'noiseceiling_task_train_n_3': noiseceiling_task_train_n_3,
        'noiseceiling_task_test_n_1': noiseceiling_task_test_n_1,
        'noiseceiling_task_test_n_10': noiseceiling_task_test_n_10,
        'correlation': correlation,
        'r2': r2,
        'explained_variance': explained_variance
        }
    }

save_dir = os.path.join(args.berg_dir, 'encoding_models', 'modality-fmri',
    'train_dataset-bmd', 'model-'+args.model, 'metadata')
os.makedirs(save_dir, exist_ok=True)

file_name = os.path.join(save_dir, f'metadata_sub-{args.subject:02d}.npy')

np.save(file_name, metadata)